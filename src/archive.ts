// `novadev archive <batch>… | --done` — move fully-recorded batches into archive/<year>/.
import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { auditLinks } from './links.ts';
import {
  BATCH_COMPLETE_FILE,
  BATCH_RE,
  addDays,
  applyFix,
  archiveGraceDays,
  batchCompletedOn,
  batchIsDone,
  daysSince,
  fail,
  listDirs,
  listTestTasks,
  novadevDir,
  requireProjectRoot,
  todayStamp,
  todoState,
} from './lib.ts';

/**
 * Archiving changes what the derived blocks say (a work line gains "· archived"), so
 * regenerate them here — otherwise every archive sweep leaves `novadev doctor` failing
 * until someone remembers to run `novadev links --fix` by hand.
 */
function regenerateDerived(root: string, quiet = false): void {
  const { fixes } = auditLinks(root);
  for (const fix of fixes) applyFix(fix);
  if (fixes.length > 0 && !quiet) console.log(`regenerated ${fixes.length} derived file(s).`);
}

/**
 * The whole `--done` sweep as a callable unit: reviewed test rounds, then every
 * fully-recorded batch, then the derived-content regeneration the moves invalidate.
 * `novadev sync` drives this; the CLI command is a thin wrapper that prints.
 */
export function sweepDone(root: string): string[] {
  const nd = novadevDir(root);
  const moved: string[] = [];
  const log = (line: string) => moved.push(line);

  for (const task of listTestTasks(nd)) {
    if (task.status !== 'reviewed') continue;
    const date = (task.lastTested || task.fm.updated || todayStamp()).slice(0, 10);
    const year = date.slice(0, 4);
    const round = `rev${task.revision || 1}-${date}`;
    const dest = join(nd, 'archive', year, 'totest', task.id, round);
    if (existsSync(dest)) fail(`archive already contains ${year}/totest/${task.id}/${round}`);
    mkdirSync(join(dest, '..'), { recursive: true });
    renameSync(task.dir, dest);
    log(`totest/${task.id} → archive/${year}/totest/${task.id}/${round}`);
  }

  for (const line of sweepBatches(nd)) log(line);
  if (moved.length > 0) regenerateDerived(root, true);
  return moved;
}

/**
 * Finished batches are marked with an autogenerated `completed.md` and then LEFT in
 * `todos/` for the grace period, so recent work stays where you look for it and the
 * next same-day batch number is visible rather than hidden in the archive. Only once
 * a batch is older than the grace does it actually move.
 */
export function sweepBatches(nd: string): string[] {
  const moved: string[] = [];
  const todosDir = join(nd, 'todos');
  const grace = archiveGraceDays(nd);
  const today = todayStamp();

  for (const batch of listDirs(todosDir)) {
    const batchDir = join(todosDir, batch);
    const markerPath = join(batchDir, BATCH_COMPLETE_FILE);

    if (!batchIsDone(batchDir)) {
      // Reopened (a new todo, or a gate that swung back) — the marker would be a lie.
      if (existsSync(markerPath)) rmSync(markerPath);
      continue;
    }

    const completedOn = batchCompletedOn(batchDir) ?? today;
    writeFileSync(markerPath, completedMarker(batch, batchDir, completedOn, grace));

    if (daysSince(completedOn) < grace) continue;

    const m = batch.match(BATCH_RE);
    if (!m) continue;
    const destDir = join(nd, 'archive', m[1], 'todos');
    mkdirSync(destDir, { recursive: true });
    const dest = join(destDir, batch);
    if (existsSync(dest)) {
      fail(
        `archive already contains ${m[1]}/todos/${batch} — todos/${batch} is a duplicate name.\n` +
          `  Rename it to the next free number for that day, then run \`novadev sync\` again.`,
      );
    }
    rmSync(markerPath, { force: true }); // the marker only means "waiting in todos/"
    renameSync(batchDir, dest);
    moved.push(`todos/${batch} → archive/${m[1]}/todos/${batch}`);
  }
  return moved;
}

/** The autogenerated batch marker: tells agents it is done, and the human when it goes. */
function completedMarker(batch: string, batchDir: string, completedOn: string, grace: number): string {
  const mark: Record<string, string> = {
    confirmed: '✓✓',
    completed: '✓',
    failed: '✗',
    needstest: '⧗',
    progress: '…',
    open: '·',
  };
  const rows = listDirs(batchDir).map((t) => {
    const state = todoState(join(batchDir, t));
    return `- ${mark[state] ?? '?'} ${t} — ${state}`;
  });
  const archiveOn = addDays(completedOn, grace);
  return `---
completed: ${completedOn}
archive-after: ${archiveOn}
---

# Batch complete — ${batch}

<!-- AUTOGENERATED by \`novadev sync\`. Do not edit; it is rewritten from the records.
     This batch is finished. It stays in todos/ for ${grace} day(s) so recent work is
     still easy to look back at, then archives itself. -->

Every todo here is recorded — **there is nothing left to do in this batch.** Do not
re-run it, and do not add new work to it: a new request gets a NEW batch.

${rows.join('\n')}

Archives to \`archive/${batch.slice(0, 4)}/todos/${batch}/\` on ${archiveOn}, on the
next \`novadev sync\` after that date.
`;
}

export function archive(args: string[]): void {
  const root = requireProjectRoot();
  const nd = novadevDir(root);
  const todosDir = join(nd, 'todos');
  const explicit = args.filter((a) => !a.startsWith('--'));

  if (args.includes('--done')) {
    const moved = sweepDone(root);
    if (moved.length === 0) {
      const waiting = listDirs(todosDir).filter(
        (b) => batchIsDone(join(todosDir, b)) && batchCompletedOn(join(todosDir, b)),
      );
      console.log(
        waiting.length > 0
          ? `nothing to archive yet — ${waiting.length} finished batch(es) are inside the ${archiveGraceDays(nd)}-day grace window (see their ${BATCH_COMPLETE_FILE}).`
          : 'nothing to archive.',
      );
      return;
    }
    for (const line of moved) console.log(`archived ${line}`);
    console.log('remember to commit the move.');
    return;
  }

  if (explicit.length === 0) fail('usage: novadev archive <batch>… | --done');

  // Naming a batch explicitly is an override: it archives now, grace or not.
  for (const batch of explicit) {
    const src = join(todosDir, batch);
    if (!existsSync(src)) fail(`batch not found: todos/${batch}`);
    const m = batch.match(BATCH_RE);
    if (!m) fail(`batch name "${batch}" does not match YYYY-MM-DD_N`);
    if (!batchIsDone(src)) {
      fail(
        `batch ${batch} is not fully recorded — every todo folder needs a terminal record (run \`novadev status\`).`,
      );
    }
    const destDir = join(nd, 'archive', m![1], 'todos');
    mkdirSync(destDir, { recursive: true });
    const dest = join(destDir, batch);
    if (existsSync(dest)) fail(`archive already contains ${m![1]}/todos/${batch}`);
    rmSync(join(src, BATCH_COMPLETE_FILE), { force: true });
    renameSync(src, dest);
    console.log(`archived todos/${batch} → archive/${m![1]}/todos/${batch}`);
  }
  regenerateDerived(root);
  console.log('remember to commit the move.');
}
